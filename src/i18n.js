/** Translate one label; falls back to the English so a missing key renders
 *  readable rather than blank. Blank is worse than English. */
// Case-insensitive second lookup, and it earns its place: this codebase
// renders the same words in several casings — a card shows NOT BILLABLE, the
// map holds 'Not billable'; the rail passes 'Needs Attention', the map holds
// 'Needs attention'. An exact-match miss does not throw, it silently ships
// ENGLISH, which is invisible until someone photographs the screen. Both of
// those were live when this was written.
const HE_CI = new Map(Object.keys(HE).map((k) => [k.toLowerCase(), HE[k]]));

export function tr(lang, s) {
  if (lang !== 'he' || typeof s !== 'string') return s;
  const hit = HE[s];
  if (hit !== undefined) return hit;
  const ci = HE_CI.get(s.toLowerCase());
  return ci !== undefined ? ci : s;
}

/** `const t = useT();` then `t('PROGRAM')`. */
export function useT() {
  const lang = useContext(LangCtx);
  return (s) => tr(lang, s);
}

/** A label for a BUTTON or TAB. Ohad's rule (2026-09-11): every button is the
 *  same size in Hebrew as in English. A Hebrew word is usually shorter, so a
 *  text-sized button shrinks. This stacks the English label, invisible, under
 *  the Hebrew one in an inline grid: the box keeps the English width, the eye
 *  sees Hebrew. In English it is just the string. */
export function tbFor(lang) {
  return (s) => {
    const he = tr('he', s);
    if (he === s) return s;                       // no Hebrew for it: plain text
    const shown = lang === 'he' ? he : s;
    const other = lang === 'he' ? s : he;
    return createElement('span', { style: { display: 'inline-grid', justifyItems: 'center', verticalAlign: 'top' } },
      createElement('span', { 'aria-hidden': 'true', style: { gridArea: '1 / 1', visibility: 'hidden', whiteSpace: 'nowrap' } }, other),
      createElement('span', { style: { gridArea: '1 / 1', whiteSpace: 'nowrap' } }, shown));
  };
}
// Every modal, drawer and overlay goes through createPortal(..., document.body),
// which puts it OUTSIDE .app-root and its dir attribute - so in Hebrew all 34 of
// them laid out left-to-right (seen 17.9 on Training Analysis for a real athlete:
// title on the left, 'ב־' torn off the block name). This marks <body> with the
// coach app's language while the coach tree is mounted; themes.css turns that
// into direction for body-level portals. A data attribute, not dir, so the page
// scrollbar and the athlete portal (which never mounts this) are untouched.
export function BodyLang({ lang }) {
  useEffect(() => {
    document.body.dataset.lang = lang === 'he' ? 'he' : 'en';
    return () => { delete document.body.dataset.lang; };
  }, [lang]);
  return null;
}
export function useTB() {
  return tbFor(useContext(LangCtx));
}

