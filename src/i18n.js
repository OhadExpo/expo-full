// A link may carry the language: expo-il.co.il (another origin, so its own
// storage is out of reach) sends a Hebrew reader to the demo with ?lang=he.
// The hint is kept, so the next visit without it stays Hebrew.
// THE DIRECTION OF A LINE IS SET BY ITS FIRST STRONG LETTER, NOT BY WHETHER
// IT CONTAINS ONE. The app had `contains any Hebrew character -> rtl` in ten
// places, so "Call <hebrew name> - skipped W4 of Block #15" - an English
// sentence with one Hebrew name in it - was forced right-to-left and came out
// scrambled, the dash and the block number jumping to the wrong end (Ohad's
// phone, 18.9). First-strong is the Unicode rule browsers implement for
// dir="auto", and it reads both languages correctly.
export const dirOfText = (s) => (/^[^\p{L}]*[֐-׿]/u.test(String(s || '')) ? 'rtl' : 'ltr');

export function readLang() {
  try {
    const hint = new URLSearchParams(window.location.search).get('lang');
    if (hint === 'he' || hint === 'en') { try { localStorage.setItem(LANG_KEY, hint); } catch { /* private mode */ } return hint; }
  } catch { /* no window */ }
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved === 'he' || saved === 'en') return saved;
  } catch { /* private mode */ }
  // NOBODY HAS CHOSEN YET -> ASK THE BROWSER.
  //
  // Ohad, 22.9: "make the hebrew go from 10% to over 90% on all of our
  // platforms". A big part of that 10% was not a missing translation at all:
  // this function returned 'en' for every first-time visitor, so an Israeli
  // coach or athlete opening the app for the first time got the English UI and
  // had to find a toggle. The Hebrew was already written; nobody was shown it.
  //
  // Only the FIRST visit is affected — an explicit choice is stored above and
  // always wins, in both directions. `iw` is the legacy ISO code for Hebrew and
  // some Android builds still send it.
  try {
    const tags = [navigator.language, ...(navigator.languages || [])].filter(Boolean);
    if (tags.some((t) => /^(he|iw)\b/i.test(t))) return 'he';
  } catch { /* no navigator */ }
  return 'en';
}

// Relative days. A map cannot hold these: Hebrew does not say "לפני 1 ימים",
// it says "אתמול". English "2d ago" collapses all of that into one shape.
export function daysAgoHe(n) {
  if (n <= 0) return 'היום';
  if (n === 1) return 'אתמול';
  if (n === 2) return 'שלשום';
  return `לפני ${n} ימים`;
}
// Sessions remaining. The compact rails printed `${n} ${T('LEFT')}`, which in
// Hebrew is "1 נותרו" — a plural verb on a count of one — and one of them had
// no space at all, so it read "2נותרו". Hebrew agrees the verb with the number.
export function sessionsLeftHe(n) {
  if (n <= 0) return 'לא נותרו';
  if (n === 1) return 'נותר 1';
  return `נותרו ${n}`;
}
// "5d ago" for a timestamp. The three views that show one each had their own
// ago() returning `5d`, and the Hebrew screen read `לפני 5d`.
export function agoLabel(iso, lang) {
  if (!iso) return '';
  const ms = Date.now() - new Date(iso).getTime();
  const d = Math.floor(ms / 86400000), h = Math.floor(ms / 3600000), m = Math.floor(ms / 60000);
  if (lang !== 'he') return d >= 1 ? `${d}d ago` : h >= 1 ? `${h}h ago` : m >= 1 ? `${m}m ago` : 'just now';
  if (d >= 1) return daysAgoHe(d);
  if (h >= 1) return h === 1 ? 'לפני שעה' : h === 2 ? 'לפני שעתיים' : `לפני ${h} שעות`;
  if (m >= 1) return m === 1 ? 'לפני דקה' : `לפני ${m} דקות`;
  return 'עכשיו';
}
export function daysOverdueHe(n) {
  if (n === 1) return 'באיחור של יום';
  return `באיחור של ${n} ימים`;
}

// Counted nouns. English builds "3 days" by appending an s; Hebrew does not
// pluralise that way, and a number glued to an English word also breaks
// direction inside an RTL line. So the NOUN is chosen per language.
const COUNT_HE = {
  day: ['יום', 'ימים'],
  exercise: ['תרגיל', 'תרגילים'],
  set: ['סט', 'סטים'],
  rep: ['חזרה', 'חזרות'],
  week: ['שבוע', 'שבועות'],
  program: ['תוכנית', 'תוכניות'],
  athlete: ['מתאמן', 'מתאמנים'],
  session: ['אימון', 'אימונים'],
};
export function countIn(lang, n, word) {
  const k = String(word).toLowerCase();
  if (lang === 'he' && COUNT_HE[k]) return `${n} ${COUNT_HE[k][Number(n) === 1 ? 0 : 1]}`;
  return `${n} ${word}${Number(n) === 1 ? '' : 's'}`;
}
