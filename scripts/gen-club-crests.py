"""Generated crests for the demo clubs (#968, Ohad 24.10: "the demo teams logos look awful fix it").

The old crest was a shield with three squeezed initials in Arial Black and a 9.5px club name: at the 28px it is shown
in the zone header it read as a blob. These are badges built to be read at 28px: one monogram letter, two club colours,
a faint sport motif clipped inside, no small text. The letter is the OUTLINE of Nord Bold (the brand face), taken from
public/fonts/Nord-Bold.woff2, so the badge looks the same on every phone - an <img> of an SVG cannot load a web font.

    python scripts/gen-club-crests.py   -> src/clubs/crests.js   then   node scripts/gen-club-assets.mjs (tab icons + share cards)
Fictional clubs only (GALIL, SHARON) and a generated badge in Netanya's colours - never a real club's artwork.
"""
import os
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.transformPen import TransformPen

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT = TTFont(os.path.join(ROOT, 'public', 'fonts', 'Nord-Bold.woff2'))
GS = FONT.getGlyphSet()
CMAP = FONT.getBestCmap()

def letter(ch, cx, cy, height):
    """The glyph's outline as an SVG path, scaled to `height` (cap height) and centred on (cx, cy)."""
    name = CMAP[ord(ch)]
    bp = BoundsPen(GS); GS[name].draw(bp)
    x0, y0, x1, y1 = bp.bounds
    s = height / (y1 - y0)
    # font units are y-up: flip, scale, then centre the ink box on (cx, cy)
    tx = cx - (x0 + x1) / 2 * s
    ty = cy + (y0 + y1) / 2 * s
    pen = SVGPathPen(GS)
    GS[name].draw(TransformPen(pen, (s, 0, 0, -s, tx, ty)))
    return pen.getCommands()

SHIELD = 'M12 8 H88 Q92 8 92 12 V60 C92 88 73 106 50 114 C27 106 8 88 8 60 V12 Q8 8 12 8 Z'

def basketball(ink):
    # the ball's seams, big and faint behind the letter
    return (f'<g fill="none" stroke="{ink}" stroke-width="3" opacity="0.22">'
            f'<circle cx="50" cy="62" r="40"/><path d="M50 22 V102 M10 62 H90"/>'
            f'<path d="M22 33 C38 48 38 76 22 91"/><path d="M78 33 C62 48 62 76 78 91"/></g>')

def football(ink):
    # a ball's panels: one pentagon and its five seams
    import math
    pts = [(50 + 15 * math.cos(math.radians(-90 + 72 * i)), 62 + 15 * math.sin(math.radians(-90 + 72 * i))) for i in range(5)]
    pent = ' '.join(f'{x:.1f},{y:.1f}' for x, y in pts)
    seams = ''.join(f'<path d="M{x:.1f} {y:.1f} L{50 + 34 * math.cos(math.radians(-90 + 72 * i)):.1f} {62 + 34 * math.sin(math.radians(-90 + 72 * i)):.1f}"/>' for i, (x, y) in enumerate(pts))
    return (f'<g fill="none" stroke="{ink}" stroke-width="3" opacity="0.22" stroke-linejoin="round">'
            f'<circle cx="50" cy="62" r="40"/><polygon points="{pent}" fill="{ink}" fill-opacity="0.6"/>{seams}</g>')

def crest(c):
    motif = basketball(c['ring']) if c['sport'] == 'basketball' else football(c['ring'])
    return ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 120">'
            f'<defs><clipPath id="s"><path d="{SHIELD}"/></clipPath></defs>'
            f'<path d="{SHIELD}" fill="{c["bg"]}"/>'
            f'<g clip-path="url(#s)">{motif}'
            # a band across the top in the second colour: the club's two colours read even at 28px
            f'<rect x="0" y="0" width="100" height="22" fill="{c["ring"]}"/></g>'
            f'<path d="{SHIELD}" fill="none" stroke="{c["ring"]}" stroke-width="5" stroke-linejoin="round"/>'
            f'<path d="{letter(c["mono"], 50, 66, 46)}" fill="{c["ink"]}"/>'
            '</svg>')

CLUBS = [
    {'id': 'galil', 'sport': 'basketball', 'bg': '#2E1A47', 'ring': '#F2B705', 'ink': '#FFFFFF', 'mono': 'G'},
    {'id': 'sharon', 'sport': 'football', 'bg': '#0F3D2E', 'ring': '#1E9E5A', 'ink': '#FFFFFF', 'mono': 'S'},
    {'id': 'netanya', 'sport': 'basketball', 'bg': '#111111', 'ring': '#FFC20E', 'ink': '#FFC20E', 'mono': 'N'},
]

if __name__ == '__main__':
    import urllib.parse
    out = {}
    for c in CLUBS:
        svg = crest(c)
        out[c['id']] = 'data:image/svg+xml;charset=utf-8,' + urllib.parse.quote(svg, safe='')
    with open(os.path.join(ROOT, 'src', 'clubs', 'crests.js'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('// GENERATED by scripts/gen-club-crests.py (#968) - do not edit; edit the generator and rerun it.\n')
        f.write('// Badges for the demo clubs: one Nord monogram, the club\'s two colours, a faint sport motif, no small text.\n')
        for k, v in out.items():
            f.write(f"export const CREST_{k.upper()} = '{v}';\n")
    print('wrote', ', '.join(out))
